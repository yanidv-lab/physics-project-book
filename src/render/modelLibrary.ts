/**
 * Blender model library.
 *
 * Every lab still builds its objects procedurally (spheres, boxes, cylinders).
 * Those meshes stay in charge of physics transforms, animation and hit-testing.
 * This module *dresses* them: it loads a Blender-authored .glb from
 * `public/models/<name>.glb`, fits it to the placeholder's bounding box,
 * attaches it as a child, and hides the placeholder's own surface.
 *
 * - If loading fails (offline, missing file, Node test env) the original
 *   procedural mesh simply stays visible.
 * - Materials named `Accent*` in Blender are replaced by the placeholder's
 *   live material, so per-frame colour / emissive changes driven by the
 *   lab (e.g. "hot", "charged", "selected") still show on the model.
 * - Model meshes are excluded from raycasting; the cheap placeholder geometry
 *   remains the hit target.
 *
 * Models are generated by `npm run models` (see blender/build_models.py).
 */
import * as THREE from 'three';
import type { GLTF } from 'three/examples/jsm/loaders/GLTFLoader.js';

/**
 * contain: uniform scale so the model fits inside the placeholder box.
 * stretch: per-axis scale to exactly fill the box.
 * x | y | z: uniform scale matching the box along one axis only (model may
 *   overhang on the others, e.g. a stand with a wide base on a thin pillar).
 * none: keep the authored size, just centre it.
 */
export type ModelFit = 'contain' | 'stretch' | 'x' | 'y' | 'z' | 'none';

export interface AttachModelOptions {
  /** How to fit the model into the placeholder's local bounding box. Default: 'contain'. */
  fit?: ModelFit;
  /** Extra uniform scale multiplier applied after fitting. */
  scale?: number;
  /** Extra local rotation (radians, XYZ) applied to the model. */
  rotation?: [number, number, number];
  /** Extra local offset applied after fitting. */
  offset?: [number, number, number];
  /** Keep the placeholder surface visible underneath the model. Default: false. */
  keepPlaceholder?: boolean;
  /** Bind Blender `Accent*` materials to the placeholder's material. Default: true. */
  bindAccent?: boolean;
}

const MODEL_ATTACHED = '__blenderModel';
const hiddenMaterial = new THREE.MeshBasicMaterial({ visible: false });
const cache = new Map<string, Promise<THREE.Object3D | null>>();
let loaderPromise: Promise<{ load: (url: string) => Promise<GLTF> } | null> | null = null;
let enabled = true;

/** Globally enable/disable Blender models (e.g. `?models=off` for debugging). */
export function setModelsEnabled(on: boolean): void {
  enabled = on;
}

function canLoad(): boolean {
  return enabled && typeof window !== 'undefined' && typeof document !== 'undefined';
}

function getLoader() {
  if (!loaderPromise) {
    loaderPromise = import('three/examples/jsm/loaders/GLTFLoader.js')
      .then(({ GLTFLoader }) => {
        const loader = new GLTFLoader();
        return { load: (url: string) => loader.loadAsync(url) };
      })
      .catch(() => null);
  }
  return loaderPromise;
}

export function modelUrl(name: string): string {
  return `./models/${name}.glb`;
}

/** Load (once) and cache the template scene for a model. Resolves null on failure. */
export function loadModel(name: string): Promise<THREE.Object3D | null> {
  if (!canLoad()) return Promise.resolve(null);
  let p = cache.get(name);
  if (!p) {
    p = getLoader().then(async (loader) => {
      if (!loader) return null;
      try {
        const gltf = await loader.load(modelUrl(name));
        return gltf.scene;
      } catch (err) {
        console.warn(`[models] could not load "${name}", keeping procedural mesh`, err);
        return null;
      }
    });
    cache.set(name, p);
  }
  return p;
}

/** Warm the cache so models appear instantly when a lab is opened. */
export function preloadModels(names: readonly string[]): void {
  for (const n of names) void loadModel(n);
}

function localBounds(obj: THREE.Object3D): THREE.Box3 {
  const mesh = obj as THREE.Mesh;
  if (mesh.isMesh && mesh.geometry) {
    if (!mesh.geometry.boundingBox) mesh.geometry.computeBoundingBox();
    return mesh.geometry.boundingBox!.clone();
  }
  return new THREE.Box3(new THREE.Vector3(-0.5, -0.5, -0.5), new THREE.Vector3(0.5, 0.5, 0.5));
}

function fitInto(model: THREE.Object3D, target: THREE.Box3, fit: ModelFit): void {
  if (fit === 'none') return;
  model.updateMatrixWorld(true);
  const src = new THREE.Box3().setFromObject(model);
  const srcSize = src.getSize(new THREE.Vector3());
  const dstSize = target.getSize(new THREE.Vector3());
  const safe = (v: number) => (v > 1e-6 ? v : 1);

  if (fit === 'stretch') {
    model.scale.set(
      (dstSize.x / safe(srcSize.x)) * model.scale.x,
      (dstSize.y / safe(srcSize.y)) * model.scale.y,
      (dstSize.z / safe(srcSize.z)) * model.scale.z,
    );
  } else if (fit === 'x' || fit === 'y' || fit === 'z') {
    model.scale.multiplyScalar(dstSize[fit] / safe(srcSize[fit]));
  } else {
    const src3 = [srcSize.x, srcSize.y, srcSize.z];
    const dst3 = [dstSize.x, dstSize.y, dstSize.z];
    const ratios = src3
      .map((sv, i) => (sv > 1e-6 && dst3[i] > 1e-6 ? dst3[i] / sv : Number.POSITIVE_INFINITY))
      .filter(Number.isFinite);
    const s = ratios.length ? Math.min(...ratios) : 1;
    model.scale.multiplyScalar(s);
  }

  model.updateMatrixWorld(true);
  const fitted = new THREE.Box3().setFromObject(model);
  const delta = target.getCenter(new THREE.Vector3()).sub(fitted.getCenter(new THREE.Vector3()));
  model.position.add(delta);
}

function placeholderMaterial(obj: THREE.Object3D): THREE.Material | null {
  const m = (obj as THREE.Mesh).material;
  if (!m) return null;
  return Array.isArray(m) ? m[0] ?? null : m;
}

/**
 * Dress `placeholder` with Blender model `name`. Safe to call before the model
 * has loaded and in non-browser environments. Returns a promise resolving to
 * the attached model root (or null if the procedural mesh was kept).
 */
export function attachModel(
  placeholder: THREE.Object3D,
  name: string,
  opts: AttachModelOptions = {},
): Promise<THREE.Object3D | null> {
  if (!canLoad()) return Promise.resolve(null);
  return loadModel(name).then((template) => {
    if (!template) return null;
    if (placeholder.userData[MODEL_ATTACHED]) return placeholder.userData[MODEL_ATTACHED] as THREE.Object3D;

    const liveMat = placeholderMaterial(placeholder);
    const root = new THREE.Group();
    root.name = `model:${name}`;
    const model = template.clone(true);
    root.add(model);

    model.traverse((child) => {
      const mesh = child as THREE.Mesh;
      if (!mesh.isMesh) return;
      mesh.raycast = () => {};
      const mat = mesh.material as THREE.Material;
      if ((opts.bindAccent ?? true) && liveMat && mat?.name?.startsWith('Accent')) {
        mesh.material = liveMat;
      }
    });

    if (opts.rotation) model.rotation.set(...opts.rotation);
    fitInto(root, localBounds(placeholder), opts.fit ?? 'contain');
    if (opts.scale) {
      const c = localBounds(placeholder).getCenter(new THREE.Vector3());
      root.position.sub(c).multiplyScalar(opts.scale).add(c);
      root.scale.multiplyScalar(opts.scale);
    }
    if (opts.offset) root.position.add(new THREE.Vector3(...opts.offset));

    placeholder.add(root);
    placeholder.userData[MODEL_ATTACHED] = root;

    const mesh = placeholder as THREE.Mesh;
    if (mesh.isMesh && !opts.keepPlaceholder) {
      mesh.userData.__proceduralMaterial = mesh.material;
      mesh.material = hiddenMaterial;
    }
    return root;
  });
}

/** Remove an attached model and restore the procedural surface. */
export function detachModel(placeholder: THREE.Object3D): void {
  const root = placeholder.userData[MODEL_ATTACHED] as THREE.Object3D | undefined;
  if (!root) return;
  placeholder.remove(root);
  delete placeholder.userData[MODEL_ATTACHED];
  const mesh = placeholder as THREE.Mesh;
  if (mesh.userData.__proceduralMaterial) {
    mesh.material = mesh.userData.__proceduralMaterial;
    delete mesh.userData.__proceduralMaterial;
  }
}
